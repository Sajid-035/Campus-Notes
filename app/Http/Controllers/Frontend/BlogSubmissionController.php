<?php

namespace App\Http\Controllers\Frontend;

use App\Http\Controllers\Controller;
use App\Models\BlogCategory;
use App\Models\BlogPost;
use DOMDocument;
use DOMElement;
use DOMNode;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use Illuminate\View\View;

class BlogSubmissionController extends Controller
{
    public function create(): View
    {
        $categories = BlogCategory::orderBy('name')->get();
        return view('frontend.blog.submit', compact('categories'));
    }

    public function store(Request $request): RedirectResponse
    {
        $data = $request->validate([
            'title' => ['required', 'string', 'max:255'],
            'category_id' => ['nullable', 'integer', 'exists:blog_categories,id'],
            'excerpt' => ['nullable', 'string', 'max:500'],
            'content' => ['required', 'string', 'max:50000'],
            'featured_image' => ['required', 'image', 'mimes:jpg,jpeg,png,webp', 'max:5120'],
            'featured_image_alt' => ['nullable', 'string', 'max:255'],
        ]);

        $plainText = trim(preg_replace('/\s+/u', ' ', html_entity_decode(strip_tags($data['content']), ENT_QUOTES | ENT_HTML5, 'UTF-8')));
        if (mb_strlen($plainText) < 100) {
            return back()->withErrors(['content' => 'Please write at least 100 characters of meaningful blog content.'])->withInput();
        }

        $base = Str::slug($data['title']) ?: 'community-post';
        $slug = $base;
        $suffix = 2;
        while (BlogPost::where('slug', $slug)->exists()) {
            $slug = $base . '-' . $suffix++;
        }

        $imagePath = $request->file('featured_image')->store('blog/community-featured', 'public');
        if (! $imagePath) {
            return back()->withErrors(['featured_image' => 'The featured image could not be uploaded. Please try again.'])->withInput();
        }

        try {
            BlogPost::create([
                'author_id' => $request->user()->id,
                'category_id' => $data['category_id'] ?? null,
                'title' => $data['title'],
                'slug' => $slug,
                'excerpt' => $data['excerpt'] ?? null,
                'content' => $this->sanitizeContent($data['content']),
                'featured_image' => $imagePath,
                'featured_image_alt' => $data['featured_image_alt'] ?? $data['title'],
                'status' => 'pending',
                'published_at' => null,
                'robots_index' => false,
                'robots_follow' => true,
                'schema_type' => 'BlogPosting',
            ]);
        } catch (\Throwable $exception) {
            Storage::disk('public')->delete($imagePath);
            throw $exception;
        }

        return redirect()->route('blog.submit')->with('success', 'Your blog post has been submitted and is waiting for admin approval.');
    }

    /**
     * Keep only safe formatting generated by the rich-text editor.
     * Script-like elements are removed entirely; unsupported formatting is unwrapped.
     */
    private function sanitizeContent(string $html): string
    {
        if (! class_exists(DOMDocument::class)) {
            // Safe fallback for hosts where PHP's DOM extension is not enabled.
            $html = preg_replace('#<(script|style|iframe|object|embed|svg|math|form|video|audio)\b[^>]*>.*?</\1\s*>#is', '', $html) ?? '';
            $html = preg_replace('#<(script|style|iframe|object|embed|svg|math|form|video|audio)\b[^>]*/?>#i', '', $html) ?? '';
            $allowed = '<p><br><strong><b><em><i><u><s><blockquote><ul><ol><li><h2><h3><h4><a><table><thead><tbody><tr><th><td><hr><pre><code>';
            $html = strip_tags($html, $allowed);

            return preg_replace_callback('/<([a-z0-9]+)\b([^>]*)>/i', function ($matches) {
                $tag = strtolower($matches[1]);
                if ($tag === 'br' || $tag === 'hr') {
                    return '<' . $tag . '>';
                }

                $kept = '';
                if ($tag === 'a' && preg_match('/\bhref\s*=\s*(?:"([^"]*)"|\'([^\']*)\'|([^\s>]+))/i', $matches[2], $hrefMatch)) {
                    $href = trim(html_entity_decode($hrefMatch[1] ?? $hrefMatch[2] ?? $hrefMatch[3] ?? '', ENT_QUOTES | ENT_HTML5, 'UTF-8'));
                    $scheme = strtolower((string) parse_url($href, PHP_URL_SCHEME));
                    $isRelative = $href !== '' && (str_starts_with($href, '/') || str_starts_with($href, '#'));
                    if ($href !== '' && ($isRelative || in_array($scheme, ['http', 'https', 'mailto'], true))) {
                        $kept .= ' href="' . e($href) . '"';
                    }
                    if (preg_match('/\btitle\s*=\s*(?:"([^"]*)"|\'([^\']*)\')/i', $matches[2], $titleMatch)) {
                        $kept .= ' title="' . e($titleMatch[1] ?? $titleMatch[2] ?? '') . '"';
                    }
                    if (preg_match('/\btarget\s*=\s*["\']_blank["\']/i', $matches[2])) {
                        $kept .= ' target="_blank" rel="noopener noreferrer"';
                    }
                } elseif (in_array($tag, ['td', 'th'], true)) {
                    foreach (['colspan', 'rowspan'] as $attribute) {
                        if (preg_match('/\b' . $attribute . '\s*=\s*["\']?(\d+)["\']?/i', $matches[2], $valueMatch)) {
                            $kept .= ' ' . $attribute . '="' . max(1, min(20, (int) $valueMatch[1])) . '"';
                        }
                    }
                }

                return '<' . $tag . $kept . '>';
            }, $html) ?? '';
        }

        $previous = libxml_use_internal_errors(true);
        $document = new DOMDocument('1.0', 'UTF-8');
        $document->loadHTML('<?xml encoding="UTF-8"><div id="blog-content-root">' . $html . '</div>', LIBXML_HTML_NOIMPLIED | LIBXML_HTML_NODEFDTD);
        libxml_clear_errors();
        libxml_use_internal_errors($previous);

        $root = $document->getElementById('blog-content-root');
        if (! $root) {
            return '<p>' . e(strip_tags($html)) . '</p>';
        }

        $this->sanitizeChildren($root);
        $clean = '';
        foreach ($root->childNodes as $child) {
            $clean .= $document->saveHTML($child);
        }

        return $clean;
    }

    private function sanitizeChildren(DOMNode $parent): void
    {
        $allowedTags = ['p', 'br', 'strong', 'b', 'em', 'i', 'u', 's', 'blockquote', 'ul', 'ol', 'li', 'h2', 'h3', 'h4', 'a', 'table', 'thead', 'tbody', 'tr', 'th', 'td', 'hr', 'pre', 'code'];
        $removeWithContents = ['script', 'style', 'iframe', 'object', 'embed', 'svg', 'math', 'form', 'input', 'button', 'textarea', 'video', 'audio'];

        // Snapshot the children because unsupported tags may be removed or unwrapped.
        $children = [];
        foreach ($parent->childNodes as $child) {
            $children[] = $child;
        }

        foreach ($children as $child) {
            if ($child->nodeType === XML_COMMENT_NODE) {
                $parent->removeChild($child);
                continue;
            }

            if (! $child instanceof DOMElement) {
                continue;
            }

            $tag = strtolower($child->tagName);
            if (in_array($tag, $removeWithContents, true)) {
                $parent->removeChild($child);
                continue;
            }

            if (! in_array($tag, $allowedTags, true)) {
                while ($child->firstChild) {
                    $parent->insertBefore($child->firstChild, $child);
                }
                $parent->removeChild($child);
                continue;
            }

            $allowedAttributes = match ($tag) {
                'a' => ['href', 'title', 'target'],
                'td', 'th' => ['colspan', 'rowspan'],
                default => [],
            };

            $attributes = [];
            foreach ($child->attributes as $attribute) {
                $attributes[] = $attribute->name;
            }

            foreach ($attributes as $attributeName) {
                if (! in_array(strtolower($attributeName), $allowedAttributes, true)) {
                    $child->removeAttribute($attributeName);
                }
            }

            if ($tag === 'a') {
                $href = trim($child->getAttribute('href'));
                $scheme = strtolower((string) parse_url($href, PHP_URL_SCHEME));
                $isRelative = $href !== '' && (str_starts_with($href, '/') || str_starts_with($href, '#'));
                if ($href !== '' && ! $isRelative && ! in_array($scheme, ['http', 'https', 'mailto'], true)) {
                    $child->removeAttribute('href');
                }
                if ($child->getAttribute('target') === '_blank') {
                    $child->setAttribute('rel', 'noopener noreferrer');
                }
            }

            $this->sanitizeChildren($child);
        }
    }
}
